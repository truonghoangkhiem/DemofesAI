export const isLang = code => Object.hasOwn(I18N, code);

// Returns the text for key in lang (falling back to the default language, then the key itself),
// with {name} placeholders replaced from params.
export function t(lang, key, params) {
  const text = I18N[lang]?.[key] ?? I18N[DEFAULT_LANG][key] ?? key;
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

// Which preset (if any) the text is, in any language: returns its key or null.
export function findPreset(text) {
  const value = text.trim();
  for (const presets of Object.values(PRESETS)) {
    for (const [key, preset] of Object.entries(presets)) if (preset === value) return key;
  }
  return null;
}
